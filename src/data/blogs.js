export function getBlogBySlug(slug) {
  return blogPosts.find((post) => post.slug === slug);
}

export function getRelatedBlogs(post, count = 3) {
  const editorialSlugs = new Set([
    "ai-product-discovery-playbook",
    "cloud-migration-without-chaos",
    "security-first-product-design",
    "data-migration-roadmap",
    "project-management-for-digital-launches",
    "scalable-web-platforms-for-growth",
    "ux-research-that-reduces-risk",
    "software-teams-that-ship-faster",
  ]);
  const editorialPosts = blogPosts.filter(
    (item) => item.slug !== post.slug && editorialSlugs.has(item.slug),
  );

  return editorialPosts
    .filter((item) => item.category === post.category)
    .concat(editorialPosts.filter((item) => item.category !== post.category))
    .slice(0, count);
}
